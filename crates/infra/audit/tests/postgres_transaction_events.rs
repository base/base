/// Production RDS is Postgres 17. `testcontainers-modules` still defaults to
/// Postgres 11, which lacks the partitioning features the schema relies on.
const POSTGRES_TAG: &str = "17-alpine";

/// Hot class day partitions of the v2 tree, which ingest writes.
const HOT_PARTITIONS_SQL: &str = "SELECT c.relname::text FROM pg_inherits i \
     JOIN pg_class c ON c.oid = i.inhrelid \
     WHERE i.inhparent = 'transaction_events_v2_hot'::regclass \
     ORDER BY c.relname";

/// Day partitions of the legacy tree, across all classes.
const LEGACY_PARTITIONS_SQL: &str = "SELECT c.relname::text FROM pg_inherits i \
     JOIN pg_class c ON c.oid = i.inhrelid \
     WHERE i.inhparent IN ('transaction_events_hot'::regclass, \
         'transaction_events_warm'::regclass, 'transaction_events_cold'::regclass) \
     ORDER BY c.relname";

/// Transaction hash shared by legacy and v2 rows in read-through tests.
const SHARED_TX_HASH: &str = "0xaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";

/// Block hash shared by legacy and v2 rows in read-through tests.
const SHARED_BLOCK_HASH: &str =
    "0xbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb";

/// Block number shared by legacy and v2 rows in read-through tests.
const SHARED_BLOCK_NUMBER: u64 = 456;

/// Bundle hash shared by legacy and v2 rows in read-through tests.
const SHARED_BUNDLE_HASH: &str = "0xbundle-shared";

/// Committed schema that the migrations must produce, from any starting state.
const SCHEMA_SNAPSHOT_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/schema.sql");

/// Set to rewrite [`SCHEMA_SNAPSHOT_PATH`] instead of comparing against it.
const UPDATE_SCHEMA_SNAPSHOT_ENV: &str = "UPDATE_SCHEMA_SNAPSHOT";

const SCHEMA_SNAPSHOT_HEADER: &str = "-- Schema produced by crates/infra/audit/migrations, excluding dated day\n\
     -- partitions and _sqlx_migrations. Generated by the postgres_transaction_events\n\
     -- tests; regenerate with UPDATE_SCHEMA_SNAPSHOT=1 instead of editing by hand.\n";

struct PostgresHarness {
    port: u16,
    database_url: String,
    container: testcontainers::ContainerAsync<Postgres>,
}

impl PostgresHarness {
    async fn new() -> anyhow::Result<Self> {
        let container = Postgres::default().with_tag(POSTGRES_TAG).start().await?;
        let port = container.get_host_port_ipv4(5432).await?;
        let database_url = format!("postgres://postgres:postgres@127.0.0.1:{port}/postgres");
        Ok(Self { port, database_url, container })
    }

    fn url_for(&self, user: &str, password: &str) -> String {
        format!("postgres://{user}:{password}@127.0.0.1:{}/postgres", self.port)
    }

    /// Normalized schema-only `pg_dump` of the database.
    ///
    /// Day partitions are excluded because their names depend on the current
    /// date. sqlx's history table and `pg_dump`'s version-specific preamble are
    /// excluded because they are not part of the audit schema.
    async fn schema_dump(&self) -> anyhow::Result<String> {
        let mut result = self
            .container
            .exec(ExecCommand::new([
                "pg_dump",
                "--username=postgres",
                "--dbname=postgres",
                "--schema-only",
                "--no-owner",
                "--exclude-table=_sqlx_migrations",
                "--exclude-table=transaction_events_*_2*",
            ]))
            .await?;
        let stdout = String::from_utf8(result.stdout_to_vec().await?)?;
        let stderr = String::from_utf8(result.stderr_to_vec().await?)?;
        anyhow::ensure!(result.exit_code().await? == Some(0), "pg_dump failed: {stderr}");

        let mut lines: Vec<&str> = Vec::new();
        for line in stdout.lines() {
            let preamble =
                ["--", "\\restrict", "\\unrestrict", "SET ", "SELECT pg_catalog.set_config"]
                    .iter()
                    .any(|prefix| line.starts_with(prefix));
            let repeated_blank = line.is_empty() && lines.last().is_none_or(|last| last.is_empty());
            if !preamble && !repeated_blank {
                lines.push(line);
            }
        }
        while lines.last().is_some_and(|last| last.is_empty()) {
            lines.pop();
        }
        Ok(format!("{SCHEMA_SNAPSHOT_HEADER}\n{}\n", lines.join("\n")))
    }

    /// Asserts the schema matches the committed snapshot, or rewrites the
    /// snapshot when [`UPDATE_SCHEMA_SNAPSHOT_ENV`] is set.
    async fn assert_schema_matches_snapshot(&self) -> anyhow::Result<()> {
        let dump = self.schema_dump().await?;
        if std::env::var_os(UPDATE_SCHEMA_SNAPSHOT_ENV).is_some() {
            std::fs::write(SCHEMA_SNAPSHOT_PATH, dump)?;
            return Ok(());
        }
        let expected = std::fs::read_to_string(SCHEMA_SNAPSHOT_PATH)?;
        assert_eq!(
            dump, expected,
            "schema differs from crates/infra/audit/schema.sql; if the change is intended, rerun with {UPDATE_SCHEMA_SNAPSHOT_ENV}=1 and review the diff"
        );
        Ok(())
    }

    /// Creates the runtime and extraction roles, so the migrations' grants
    /// appear in the schema.
    async fn create_grantee_roles(&self) -> anyhow::Result<()> {
        let pool = PgPoolOptions::new().max_connections(1).connect(&self.database_url).await?;
        pool.execute("CREATE ROLE audit_archiver NOLOGIN").await?;
        pool.execute("CREATE ROLE datapilot NOLOGIN").await?;
        Ok(())
    }
}


    sqlx::query(
        "INSERT INTO transaction_events \
         (event_id, schema_version, event_time, producer, event_type, network, data) \
         VALUES ('legacy-row', 'transaction-event/v1', now(), 'base-builder', \
                 'BUILDER_ACCEPTED', 'base-mainnet', '{}'::jsonb)",
    )
    .execute(&pool)
    .await?;

